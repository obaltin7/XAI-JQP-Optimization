# Single entry
# --------------------------------------------------------------------------- #
def run_entry(entry: Dict[str, Any], ctx: Dict[str, Any], rep: Dict[str, Any], store: ResultStore, log: Logger) -> None:
    args, dry = ctx["args"], ctx["dry"]
    key = entry["key"]
    rep.update({"status": "running", "fraction": entry["fraction"], "config": entry["config"], "seed": entry["seed"],
                "source": entry["source"], "started_at": datetime.now().isoformat(timespec="seconds")})
    store.save(f"{key} started")
    t0 = time.time()
    set_seed(args.seed)
    rep["cuda_allocated_before_load_gb"] = ensure_clean_gpu(log, key)
    if torch.cuda.is_available():
        torch.cuda.reset_peak_memory_stats()
    box: Dict[str, Any] = {}
    try:
        if dry:
            box["tokenizer"], box["model"], rep["model_load_seconds"] = dry.load_model(log)
        else:
            box["tokenizer"], box["model"], rep["model_load_seconds"] = load_model(log, dtype=DTYPES[ctx["dtype"]], model_name=ctx["model"])
        model, tok = box["model"], box["tokenizer"]
        rep["model_bytes_before"] = module_bytes(model)
        plan: Dict[int, LayerPlan] = entry["plan"]
        t_apply = time.time()
        if entry.get("bit_plan"):  # D-2 HQQ bit plan: SAME application path as run_mixed_precision (apply_hqq); no pruning / bnb
            import run_mixed_precision as mb

            fake = bool(dry) and not mb.hqq_available()
            rep["quantization"] = mb.apply_hqq(model, entry["bit_plan"], fake=fake)
            rep["quantization_path"] = "hqq (run_mixed_precision.apply_hqq)" + (" [fake, dry-run]" if fake else "")
            rep.update({"n_pruned_heads": 0, "int4_modules": 0, "hqq_modules_by_bits": rep["quantization"]["modules_by_bits"]})
            src_bits = entry["source"].get("hqq_modules_by_bits")
            if src_bits and {k: int(v) for k, v in rep["hqq_modules_by_bits"].items()} != {k: int(v) for k, v in src_bits.items()}:
                raise RuntimeError(f"{key}: applied HQQ bit plan does not match the source ({rep['hqq_modules_by_bits']} vs {src_bits})")
        elif plan:  # same order as the source runs: masked pruning -> quantisation
            rep["pruning"] = apply_structural_pruning(model, prune_only(plan), verbose=False)
            if planned_int4_modules(plan) or any(p.attn_quant == "int8" or p.mlp_quant == "int8" for p in plan.values()):
                if dry or ctx["dtype"] == "fp16":
                    rep["quantization"] = quantize_with_fallback(model, plan, log, _StoreView(store, rep), "cfg")
                else:
                    rep["quantization"] = apply_quantization(model, plan, compute_dtype=DTYPES[ctx["dtype"]], verbose=True)
            else:
                rep["quantization"] = {"int4_modules": 0, "int8_modules": 0}
            rep["n_pruned_heads"] = rep["pruning"]["pruned_heads"]
            rep["int4_modules"] = rep["quantization"]["int4_modules"]
            src = entry["source"]
            if rep["n_pruned_heads"] != len(entry["heads"]) or (src.get("int4_modules") is not None and rep["int4_modules"] != src["int4_modules"]):
                raise RuntimeError(f"{key}: applied plan does not match the source (heads {rep['n_pruned_heads']} vs {len(entry['heads'])}, "
                                   f"INT4 {rep['int4_modules']} vs {src.get('int4_modules')})")
        else:
            rep.update({"n_pruned_heads": 0, "int4_modules": 0})
        rep["apply_seconds"] = time.time() - t_apply
        rep["model_bytes_after"] = module_bytes(model)
        log(f"{key}: applied ({rep['apply_seconds']:.1f} s): {rep['n_pruned_heads']} heads, {rep['int4_modules']} INT4 modules, "
            f"{rep['model_bytes_after']['gb']:.3f} GB", tag="G9T")

        for ds in ctx.get("ppl_datasets", []):  # E-5: cross-domain perplexity; identical window layout for all entries -> pairable
            import eval_ppl_windows as epw

            t1 = time.time()
            if dry:
                g = torch.Generator().manual_seed(args.seed + (0 if ds == "wikitext2" else 1))
                w = epw.window_nlls_from_ids(model, torch.randint(1, model.config.vocab_size, (1, 120), generator=g), "cpu", max_length=32, stride=16)
            else:
                w = epw.window_nlls(model, tok, ctx["ppl_texts"][ds], next(model.parameters()).device)
            rep.setdefault("ppl", {})[ds] = {"perplexity": w["perplexity"], "n_windows": len(w["nll"]), "n_tokens": w["n_tokens"],
                                             "seconds": time.time() - t1,
                                             **({"windows": {"nll": w["nll"], "tokens": w["tokens"]}} if args.save_window_nll else {})}
            log(f"{key}: perplexity[{ds}] = {w['perplexity']:.4f} ({len(w['nll'])} windows, {time.time() - t1:.1f} s)", tag="G9T")
            store.save(f"{key} ppl {ds}")
        if args.verify_ppl:
            t1 = time.time()
            ppl = dry.perplexity(model) if dry else ctx["compute_perplexity"](model, tok, ctx["text"], next(model.parameters()).device)
            src_ppl = entry["source"].get("perplexity")
            rep["perplexity"] = ppl
            rep["perplexity_seconds"] = time.time() - t1
            rep["perplexity_minus_source"] = (ppl - src_ppl) if isinstance(src_ppl, (int, float)) and math.isfinite(ppl) else None
            log(f"{key}: perplexity = {ppl:.4f} (source {src_ppl}, difference {rep['perplexity_minus_source']})", tag="G9T")
            store.save(f"{key} perplexity")

        tlog = lambda m: log(m, tag="TASK")  # noqa: E731
        if dry:
            rep["tasks"] = eval_tasks.evaluate_tasks_dry(model, args.seed, ctx["tasks"], log=tlog)
        else:
            rep["tasks"] = eval_tasks.evaluate_tasks(model, tok, ctx["tasks"], subsets=ctx["subsets"], batch_size=args.batch_size, log=tlog)
        rep["summary"] = eval_tasks.summarize_tasks(rep["tasks"])
        store.save(f"{key} tasks")
        if args.with_mmlu:
            import eval_mmlu

            mlog = lambda m: log(m, tag="MMLU")  # noqa: E731
            if dry:
                rep["mmlu"] = eval_mmlu.evaluate_mmlu_dry(model, args.seed, log=mlog, record_questions=True)
            else:
                rep["mmlu"] = eval_mmlu.evaluate_mmlu(model, tok, subset=ctx["mmlu_subset"], prompt_style="plain",
                                                      batch_size=args.mmlu_batch_size, log=mlog, record_questions=True)
            rep["mmlu_subset_acc"] = rep["mmlu"]["mmlu_subset_acc"]
            src_acc = entry["source"].get("mmlu_subset_acc")
            rep["mmlu_minus_source"] = (rep["mmlu_subset_acc"] - src_acc) if isinstance(src_acc, (int, float)) else None
        rep["status"] = "completed"
    finally:
        rep["peak_vram_gb"] = cuda_gb("peak")
        box.clear()
        rep["cuda_allocated_after_free_gb"] = release_gpu()
        rep["seconds"] = time.time() - t0
        store.save(f"{key} finished")


def format_summary_table(entries: Dict[str, Any], tasks: List[str]) -> str:
    def f(v: Any, spec: str) -> str:
        return format(v, spec) if isinstance(v, (int, float)) else "-"

    head = f"{'entry':<30}{'head':>6}{'int4':>6}" + "".join(f"{t[:9] + ' acc':>15}{t[:9] + ' norm':>15}" for t in tasks)
    # --ppl-datasets values (rep["ppl"][ds]) get extra columns; without them the table is byte-identical to the original layout
    # (display only, the JSON is unchanged). The header layout is asserted by tests/test_ppl_windows_mini.py.
    ppl_ds = [ds for ds in ("wikitext2", "c4") if any(ds in (e.get("ppl") or {}) for e in entries.values())]
    lines = [head + f"{'mmlu':>8}{'ppl':>10}" + "".join(f"{'ppl[' + ds[:4] + ']':>11}" for ds in ppl_ds) + f"{'s':>7}  status"]
    for key, e in entries.items():
        cells = "".join(f"{f((e.get('summary') or {}).get(t, {}).get('acc'), '.3f'):>15}{f((e.get('summary') or {}).get(t, {}).get('acc_norm'), '.3f'):>15}"
                        for t in tasks)
        lines.append(f"{key:<30}{str(e.get('n_pruned_heads', '-')):>6}{str(e.get('int4_modules', '-')):>6}{cells}"
                     f"{f(e.get('mmlu_subset_acc'), '.3f'):>8}{f(e.get('perplexity'), '.4f'):>10}"
                     + "".join(f"{f(((e.get('ppl') or {}).get(ds) or {}).get('perplexity'), '.4f'):>11}" for ds in ppl_ds)
                     + f"{f(e.get('seconds'), '.0f'):>7}  {e.get('status')}")
    return "\n".join(lines)


