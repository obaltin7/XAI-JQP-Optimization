"""
Downstream-task evaluation from saved compression plans, WITHOUT recomputing attribution (GPU, or CPU with --dry-run).

The plans stored in earlier result JSONs (pruned-head list + per-layer INT4 decisions: repeats[].pruned_heads and
repeats[].plan_summary) are applied unchanged to a freshly loaded model (masked pruning -> bnb INT4, same path and order as
the original runs), then HellaSwag + ARC-Challenge are evaluated (eval_tasks: acc + acc_norm, per-question records). With
--with-mmlu the MMLU subset is re-evaluated WITH per-question records (results/iterative_gun7.json only stores per-subject
summaries). Since no scores are computed, each entry takes ~2.5-3 min.

Plan sources (--plan):
  results/iterative_gun7.json (default; Mistral)  fp16 + each fraction (0.2/0.4/0.6) x {xai_single, xai_iter_fixedq,
      prune_taylor, prune_wanda, prune_random (seed 42)} + az_buda_cok_kuantize at 20% = 17 entries. Additional
      configurations such as prune_wanda_ln can be requested with --configs. Output: results/tasks_gun9.json.
  results/model2_qwen_gun9.json (Qwen; no "fractions")  baseline + all completed configurations (prune_random: seed 42).
      Output: results/tasks_gun9_model2_qwen_gun9.json. Model id and precision are read from the plan JSON (run.model, run.dtype).
  C-3 / D-1 / D-2 plans (no fp16_rerun -> --skip-fp16; configurations outside DEFAULT_CONFIGS -> pass --configs):
    results/iterative_gun7_4tier.json      --configs xai_single_4tier,xai_iter_fixedq_4tier (int8 tier in plan_summary; bnb LLM.int8)
    results/mixed_precision_gun11.json     --configs mixed_xai_k0,mixed_xai_k10,mixed_xai_k20,mixed_random_k10,mixed_magnitude_k10 (no pruning)
    results/mixed_bits_gun11.json          repeats[].bit_plan -> run_mixed_precision.apply_hqq (HQQ; pip install hqq==0.2.8.post1);
                                           check: applied modules_by_bits == source. For stochastic configurations
                                           (mixed_random_k10, hqq_random_b*) seeds 43 / 44 are selected with --random-seed and
                                           written to a separate file (..._seed<N>.json; found automatically by compare_tasks_paired).

Verification: the applied head count and INT4 module count are compared with the source run (mismatch -> error);
--verify-ppl additionally measures WikiText-2 perplexity and records the difference from the source (~70 s/entry; numerical
evidence that the plan was reproduced exactly).

Runtime estimate on an L40S: load ~13 s + apply (INT4 ~35 s) + HellaSwag ~40-70 s + ARC ~20-40 s ≈ 2-3 min/entry;
17 entries ≈ 45-55 min (--with-mmlu: +~2.5 min/entry; --verify-ppl: +~1.2 min/entry). Peak VRAM ~16-17 GB.

Usage:
    python experiments/run_eval_from_plans.py --dry-run          # mini model; the plan JSON is generated by a dry run (dryrun_out/)
    python experiments/run_eval_from_plans.py --preflight        # check plan + subsets + CUDA (model not loaded)
    python experiments/run_eval_from_plans.py --with-mmlu        # Mistral plans -> results/tasks_gun9.json, log_gun9_tasks.txt
    python experiments/run_eval_from_plans.py --plan results/model2_qwen_gun9.json --with-mmlu      # Qwen
    python experiments/run_eval_from_plans.py --resume           # skip completed entries
"""

