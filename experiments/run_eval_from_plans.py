def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    os.makedirs(os.path.dirname(args.log) or ".", exist_ok=True)
    log = Logger(args.log, to_file=should_log_to_file(args, LOG_FILE))  # dry-run/preflight never write to the default log
    store = ResultStore(args.output, log)
    t_start = time.time()
    tasks = [t.strip() for t in args.tasks.split(",") if t.strip()]
    unknown = [t for t in tasks if t not in eval_tasks.TASK_SPECS]
    if unknown:
        raise SystemExit(f"unknown task(s): {unknown}; valid: {list(eval_tasks.ALL_TASKS)}")
    if args.dry_run and os.path.normpath(args.plan) == os.path.normpath(DEFAULT_PLAN):  # the real plan has 7B dimensions: build a mini plan
        args.plan = os.path.join(os.path.dirname(args.output) or DRYRUN_DIR, "plan_for_tasks_dry.json")
        make_dry_plan(args.plan, log)
    if not os.path.exists(args.plan):
        raise SystemExit(f"plan file not found: {args.plan}")
    with open(args.plan, "r", encoding="utf-8") as f:
        plan_json = json.load(f)
    fractions = [x.strip() for x in args.fractions.split(",") if x.strip()] if args.fractions else None
    configs = [x.strip() for x in args.configs.split(",") if x.strip()] if args.configs else None
    entries = collect_entries(plan_json, fractions, configs, include_fp16=not args.skip_fp16, random_seed=args.random_seed)
    run_meta = plan_json.get("run", {})
    model_name = args.model or (run_meta.get("model") if not args.dry_run else None) or MODEL_NAME
    dtype = args.dtype or run_meta.get("dtype") or "fp16"
    dry: Optional[DryRun] = make_dry(plan_json, args.seed) if args.dry_run else None
    per_entry = 2.5 + (2.5 if args.with_mmlu else 0.0) + (1.2 if args.verify_ppl else 0.0)
    log(f"===== Task evaluation starting: plan={args.plan} model={'mini (dry-run)' if dry else model_name} dtype={dtype} "
        f"tasks={tasks} entries={len(entries)} with_mmlu={args.with_mmlu} verify_ppl={args.verify_ppl} dry_run={args.dry_run} =====", tag="G9T")
    log(f"Entries: {[e['key'] for e in entries]}", tag="G9T")
    log(f"Time estimate: ~{per_entry:.1f} min/entry × {len(entries)} = ~{per_entry * len(entries):.0f} min", tag="G9T")

    previous = None
    if args.resume and os.path.exists(args.output):
        with open(args.output, "r", encoding="utf-8") as f:
            previous = json.load(f)
        log(f"--resume: read {args.output}; completed entries will be skipped", tag="G9T")

    store.data = {
        "run": {"started_at": datetime.now().isoformat(timespec="seconds"), "status": "running", "args": vars(args),
                "model": "mini (dry-run)" if dry else model_name, "dtype": dtype, "env": env_info(), "tasks": tasks,
                "entry_order": [e["key"] for e in entries],
                "time_estimate": {"minutes_per_entry": per_entry, "total_minutes": per_entry * len(entries)}},
        "source": {"plan_file": args.plan, "plan_model": run_meta.get("model"), "plan_format": "fractions" if "fractions" in plan_json else "configs",
                   "random_seed": args.random_seed,
                   "note": "plans taken from repeats[].pruned_heads + plan_summary of the source run; no attribution; "
                           "masked pruning (apply_structural_pruning), bnb NF4 quantisation (same path as the source runs)"},
        "entries": {e["key"]: {"status": "pending"} for e in entries},
    }

    if args.preflight:
        problems: List[str] = []
        if not dry and not torch.cuda.is_available():
            problems.append("CUDA not available")
        if not entries or (len(entries) == 1 and entries[0]["key"] == "fp16"):
            problems.append("no completed configuration to evaluate in the plan")
        for e in entries:
            log(f"  {e['key']:<30} head={len(e['heads']):>4} INT4={planned_int4_modules(e['plan']):>4} seed={e['seed']} "
                f"source ppl={e['source'].get('perplexity')} mmlu={e['source'].get('mmlu_subset_acc')}", tag="G9T")
        if not dry:
            for t in tasks:
                try:
                    s = eval_tasks.load_or_build_task_subset(t, log=lambda m: log(m, tag="TASK"))
                    log(f"{t} subset ready: {len(s['records'])} examples (sha1 verified)", tag="TASK")
                except Exception as e:
                    problems.append(f"could not load {t} subset: {e!r}")
            if args.with_mmlu:
                try:
                    import eval_mmlu

                    log(f"MMLU subset ready: {len(eval_mmlu.load_or_build_subset(log=lambda m: log(m, tag='MMLU'))['records'])} questions", tag="MMLU")
                except Exception as e:
                    problems.append(f"could not load MMLU subset: {e!r}")
        if problems:
            log("Preflight FAILED (model not loaded): " + "; ".join(problems), tag="ERR")
            return 1
        log("Preflight completed (model not loaded). Nothing written to the result file.", tag="G9T")
        return 0
    if not torch.cuda.is_available() and not dry:
        log("WARNING: CUDA not available; a 7B model + bitsandbytes does not run on CPU. Run on a GPU (or use --dry-run).", tag="G9T")
    store.save("start")

    ctx: Dict[str, Any] = {"args": args, "dry": dry, "tasks": tasks, "model": model_name, "dtype": dtype}
    ctx["ppl_datasets"] = [d.strip() for d in (args.ppl_datasets or "").split(",") if d.strip()]
    bad = [d for d in ctx["ppl_datasets"] if d not in ("wikitext2", "c4")]
    if bad:
        raise SystemExit(f"--ppl-datasets: unknown dataset {bad}; valid: wikitext2, c4")
    exit_code = 0
    try:
        if not dry:
            ctx["subsets"] = {t: eval_tasks.load_or_build_task_subset(t, log=lambda m: log(m, tag="TASK")) for t in tasks}
            store.data["source"]["subsets"] = {t: {k: s["meta"].get(k) for k in ("dataset", "config", "split", "seed", "n")}
                                               for t, s in ctx["subsets"].items()}
            if args.with_mmlu:
                import eval_mmlu

                ctx["mmlu_subset"] = eval_mmlu.load_or_build_subset(log=lambda m: log(m, tag="MMLU"))
            if ctx["ppl_datasets"]:
                import eval_ppl_windows as epw

                ctx["ppl_texts"] = {}
                for ds in ctx["ppl_datasets"]:
                    if ds == "wikitext2":
                        ctx["ppl_texts"][ds] = load_wikitext_text()
                    else:
                        ctx["ppl_texts"][ds], store.data["source"]["c4_ppl_subset"] = epw.load_c4_eval_text()
            if args.verify_ppl:
                ctx["text"] = load_wikitext_text()
                ctx["compute_perplexity"], _, _ = perplexity_tools()
        for i, entry in enumerate(entries, 1):
            key = entry["key"]
            prev = (previous or {}).get("entries", {}).get(key)
            if prev and prev.get("status") == "completed":
                store.data["entries"][key] = {**prev, "resumed": True}
                log(f"ENTRY {i}/{len(entries)} {key}: --resume, taken from the previous run", tag="G9T")
                continue
            log(f"===== ENTRY {i}/{len(entries)}: {key} ({len(entry['heads'])} heads, {planned_int4_modules(entry['plan'])} INT4 modules) =====", tag="G9T")
            rep = store.data["entries"][key]
            try:
                run_entry(entry, ctx, rep, store, log)
                log(f"ENTRY {i}/{len(entries)} DONE: {key} {json.dumps(rep['summary'])} mmlu={rep.get('mmlu_subset_acc')} {rep['seconds']:.0f} s", tag="G9T")
            except Exception as e:  # a failing entry must not abort the others
                rep.update({"status": "failed", "error": repr(e), "traceback": traceback.format_exc()})
                log(f"ENTRY {key} ERROR: {e!r} — continuing with the next entry", tag="ERR")
                log(rep["traceback"], tag="ERR")
                exit_code = 1
                store.save(f"{key} error")
        store.data["run"]["status"] = "completed" if exit_code == 0 else "completed_with_failures"
    except BaseException as e:  # including KeyboardInterrupt / SystemExit: never lose partial results
        store.data["run"].update({"status": "failed", "error": repr(e), "traceback": traceback.format_exc()})
        log(f"ERROR: {e!r} — writing partial results to disk", tag="ERR")
        log(store.data["run"]["traceback"], tag="ERR")
        exit_code = 1
    finally:
        store.data["run"]["finished_at"] = datetime.now().isoformat(timespec="seconds")
        store.data["run"]["total_seconds"] = time.time() - t_start
        store.save("final")
        log("SUMMARY TABLE:\n" + format_summary_table(store.data["entries"], tasks), tag="G9T")
        log(f"===== Finished: status={store.data['run']['status']}, total {store.data['run']['total_seconds']:.1f} s =====", tag="G9T")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
